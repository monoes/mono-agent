// decodePassthrough decodes b into dst (a pointer to a struct alias with no
// custom methods) and stores every key dst's json tags don't name into
// *extra.
func decodePassthrough(b []byte, dst interface{}, extra *map[string]json.RawMessage) error {
	if err := json.Unmarshal(b, dst); err != nil {
		return err
	}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	known := jsonKeysOf(reflect.TypeOf(dst).Elem())
	out := map[string]json.RawMessage{}
	for k, val := range raw {
		if !known[k] {
			out[k] = val
		}
	}
	if len(out) == 0 {
		out = nil
	}
	*extra = out
	return nil
}

// encodePassthrough marshals v (a struct alias) and merges extra back in.
// With no extra keys the output keeps field declaration order; otherwise
// keys are sorted, as Doc and Role already do.
func encodePassthrough(v interface{}, extra map[string]json.RawMessage) ([]byte, error) {
	base, err := json.Marshal(v)
	if err != nil {
		return nil, err
	}
	if len(extra) == 0 {
		return base, nil
	}
	var m map[string]json.RawMessage
	if err := json.Unmarshal(base, &m); err != nil {
		return nil, err
	}
	for k, val := range extra {
		if _, modeled := m[k]; modeled {
			continue
		}
		m[k] = val
	}
	return marshalOrderedMap(m)
}

var jsonKeysCache sync.Map // reflect.Type -> map[string]bool

// jsonKeysOf returns the JSON key names t's exported fields map to.
func jsonKeysOf(t reflect.Type) map[string]bool {
	if cached, ok := jsonKeysCache.Load(t); ok {
		return cached.(map[string]bool)
	}
	keys := map[string]bool{}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.PkgPath != "" {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name := strings.Split(tag, ",")[0]
		if name == "" {
			name = f.Name
		}
		keys[name] = true
	}
	jsonKeysCache.Store(t, keys)
	return keys
}

// ─── Role helpers ────────────────────────────────────────────────────────

// IsEndpoint reports whether r is an endpoint (automation) role.
func (r *Role) IsEndpoint() bool { return r.Kind == RoleKindEndpoint }

// IsHolding reports whether d is a holding org.
func (d *Doc) IsHolding() bool { return d.Kind == OrgKindHolding }

// FindAutomation returns the membership entry with alias, or nil.
func (d *Doc) FindAutomation(alias string) *AutomationRef {
	for i := range d.Automations {
		if d.Automations[i].Alias == alias {
			return &d.Automations[i]
		}
	}
	return nil
}

// FindGrantSpec returns r's display grant for alias, or nil.
func (r *Role) FindGrantSpec(alias string) *GrantSpec {
	for i := range r.Automations {
		if r.Automations[i].Alias == alias {
			return &r.Automations[i]
		}
	}
	return nil
}

// Policy returns a copy of r's policy object's keys (Extra["policy"]), or
// an empty map when the role has none or it isn't an object.
func (r *Role) Policy() map[string]json.RawMessage {
	out := map[string]json.RawMessage{}
	if raw, ok := r.Extra["policy"]; ok {
		_ = json.Unmarshal(raw, &out)
		if out == nil {
			out = map[string]json.RawMessage{}
		}
	}
	return out
}

// SetPolicy writes p back as r's policy object; an empty map removes it.
func (r *Role) SetPolicy(p map[string]json.RawMessage) {
	if len(p) == 0 {
		delete(r.Extra, "policy")
		return
	}
	b, err := marshalOrderedMap(p)
	if err != nil {
		return
	}
	if r.Extra == nil {
		r.Extra = map[string]json.RawMessage{}
	}
	r.Extra["policy"] = b
}

// PolicyStrings returns policy[key] as a string list (nil when absent or not
// a string array).
func (r *Role) PolicyStrings(key string) []string {
	raw, ok := r.Policy()[key]
	if !ok {
		return nil
	}
	var out []string
	if err := json.Unmarshal(raw, &out); err != nil {
		return nil
	}
	return out
}

// SetPolicyStrings sets policy[key] to vals (sorted, de-duplicated); an
// empty vals removes the key.
func (r *Role) SetPolicyStrings(key string, vals []string) {
	p := r.Policy()
	vals = sortedUnique(vals)
	if len(vals) == 0 {
		delete(p, key)
	} else {
		b, _ := json.Marshal(vals)
		p[key] = b
	}
	r.SetPolicy(p)
}

func sortedUnique(in []string) []string {
	seen := map[string]bool{}
	out := make([]string, 0, len(in))
	for _, s := range in {
		if s == "" || seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

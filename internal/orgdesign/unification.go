// Org × workflow unification keys (docs/plans/2026-09-15-org-workflow-unification.md
// §6.1, contracts doc §7). Every one is optional and passthrough for
// monomind. Each nested type keeps its own Extra bucket so a key added later
// by monomind or by hand survives a Load→Save cycle, the same guarantee Doc
// and Role already give at their own level.

// Org kinds.
const (
	OrgKindStandard = "standard"
	OrgKindHolding  = "holding"
)

// Role kinds.
const (
	RoleKindAgent    = "agent"
	RoleKindEndpoint = "endpoint"
)

// AutomationRef is one entry of an org's automations[] membership list: a
// workflow that belongs to the org, addressed inside it by Alias.
type AutomationRef struct {
	WorkflowID string `json:"workflow_id"`
	Alias      string `json:"alias"`
	Owned      bool   `json:"owned,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// GrantSpec is one entry of roles[].automations[] — the display copy of a
// grant. Enforcement always reads the org_grants row (internal/orggrant);
// reconcile strips any entry that has no live row.
type GrantSpec struct {
	Alias          string          `json:"alias"`
	Mode           string          `json:"mode,omitempty"` // run | trigger | status
	Wait           *bool           `json:"wait,omitempty"`
	TimeoutSeconds int             `json:"timeout_seconds,omitempty"`
	Approval       string          `json:"approval,omitempty"` // none | required
	InputSchema    json.RawMessage `json:"input_schema,omitempty"`
	MaxCallsPerRun int             `json:"max_calls_per_run,omitempty"`
	MaxCallsPerDay int             `json:"max_calls_per_day,omitempty"`
	MaxOutputBytes int             `json:"max_output_bytes,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// ToolProvider is one entry of roles[].tool_providers[] (monomind M1). The
// entry named ProviderName is generated by mono-agent; any other entry is
// left alone.
type ToolProvider struct {
	Kind      string            `json:"kind"`
	Name      string            `json:"name"`
	Command   string            `json:"command"`
	Args      []string          `json:"args"`
	Env       map[string]string `json:"env,omitempty"`
	Allow     []string          `json:"allow,omitempty"`
	Prefix    string            `json:"prefix,omitempty"`
	TimeoutMS int               `json:"timeout_ms,omitempty"`
	IdleMS    int               `json:"idle_ms,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// ProviderName is the name (and prefix) of the tool provider mono-agent
// generates for granted roles.
const ProviderName = "monoagent"

// Endpoint is an endpoint role's delivery target (monomind M2).
type Endpoint struct {
	URL            string `json:"url"`
	CredentialFile string `json:"credential_file,omitempty"`
	TimeoutMS      int    `json:"timeout_ms,omitempty"`
	InputHint      string `json:"input_hint,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// EndpointAutomation is mono-agent's own half of an automation role: which
// workflow answers messages sent to it, and what it replies with.
type EndpointAutomation struct {
	WorkflowID string `json:"workflow_id"`
	Reply      string `json:"reply,omitempty"` // last_node | node:<name>
	Alias      string `json:"alias,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// ChildOrg is one entry of a holding org's children[].
type ChildOrg struct {
	Org         string   `json:"org"`
	Start       string   `json:"start,omitempty"` // on_demand | with_parent | manual
	BudgetShare *float64 `json:"budget_share,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// Federation is the cross-root messaging policy enforced by monomind M4.
type Federation struct {
	AllowFrom []string `json:"allow_from,omitempty"`
	AllowTo   []string `json:"allow_to,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// Autonomy is the display copy of an org's autonomy settings (plan §7.7).
// The decision service enforces from the org_autonomy row; reconcile only
// ever copies a lower level from here into it.
type Autonomy struct {
	Level            string            `json:"level,omitempty"` // manual | mid | full
	Decider          *Decider          `json:"decider,omitempty"`
	Tiers            map[string]string `json:"tiers,omitempty"`
	Policy           string            `json:"policy,omitempty"`
	OnDeciderFailure string            `json:"on_decider_failure,omitempty"` // deny | human
	Limits           *AutonomyLimits   `json:"limits,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// Decider selects who resolves decisions the level routes away from a rule
// or a human.
type Decider struct {
	Kind           string `json:"kind,omitempty"` // model | boss | parent | jev
	Runtime        string `json:"runtime,omitempty"`
	Model          string `json:"model,omitempty"`
	Fallback       string `json:"fallback,omitempty"`
	TimeoutSeconds int    `json:"timeout_seconds,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

// AutonomyLimits caps decider use per org run.
type AutonomyLimits struct {
	MaxDecisionsPerRun  int     `json:"max_decisions_per_run,omitempty"`
	MaxDeciderUSDPerRun float64 `json:"max_decider_usd_per_run,omitempty"`

	Extra map[string]json.RawMessage `json:"-"`
}

